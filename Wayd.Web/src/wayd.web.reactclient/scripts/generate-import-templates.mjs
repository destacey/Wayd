/**
 * Regenerates src/components/common/import/import-templates.generated.ts from the API's OpenAPI document.
 *
 * Run after the API's Debug build has regenerated the document (and wayd-api.ts beside it):
 *   npm run generate:import-templates
 */
import * as fs from 'node:fs'
import * as path from 'node:path'
import * as prettier from 'prettier'
import { buildImportTemplates } from './import-templates.mjs'

const SPEC_PATH = path.join(
  process.cwd(),
  '..',
  'Wayd.Web.Api',
  'wwwroot',
  'api',
  'v1',
  'specification.json',
)

const OUTPUT_PATH = path.join(
  process.cwd(),
  'src',
  'components',
  'common',
  'import',
  'import-templates.generated.ts',
)

const spec = JSON.parse(fs.readFileSync(SPEC_PATH, 'utf8'))
const templates = buildImportTemplates(spec)

const source = `// Generated by scripts/generate-import-templates.mjs from the API's OpenAPI document. Do not edit:
// change the import's row class or its [CsvValues] attributes, rebuild the API, and regenerate.
import type { ImportTemplate } from './import-template'

export const importTemplates = ${JSON.stringify(templates, null, 2)} as const satisfies Record<string, ImportTemplate>

export type ImportKey = keyof typeof importTemplates
`

// editorconfig as well, as the Prettier CLI reads it: it sets the line endings.
const options =
  (await prettier.resolveConfig(OUTPUT_PATH, { editorconfig: true })) ?? {}
const formatted = await prettier.format(source, {
  ...options,
  filepath: OUTPUT_PATH,
})

fs.writeFileSync(OUTPUT_PATH, formatted)
console.log(
  `Wrote ${Object.keys(templates).length} import templates to ${path.relative(process.cwd(), OUTPUT_PATH)}`,
)
